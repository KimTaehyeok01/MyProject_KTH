// 자바는 클래스로 시작해서 클래스로 끝난다.
// public : 접근제한자(공개)
// class : 클래스 선언 예약어
// ex01 : 클래스 이름
// {} : block 구분자, 클래스, 함수, 배열 등에 사용됨
// static : 정적 변수, 함수에 사용된다.
//        : 프로그램 실핼시 고정된 주소값을 사용값 사용.
// String[] args : 문자열 배열을 의미함.
// args : 매개변수 이름.
public class ex01 {
    // Entry Point : 프로그램 시작점
    public static void main(String[] args){

        System.out.println("hello java");
    }
}
