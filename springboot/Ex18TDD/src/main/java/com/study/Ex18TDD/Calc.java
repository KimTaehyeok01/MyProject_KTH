package com.study.Ex18TDD;

// 사칙 연산 계산기
public class Calc {
    public int add(int x, int y){
        return x + y;
    }

    public int sub(int x, int y){
        return x - y;
    }

    public int mul(int x, int y){
        return x * y;
    }

    public int dev(int x, int y){
        return x / y;
    }
}
