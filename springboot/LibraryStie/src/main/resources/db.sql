USE mydb;

-- 순서 중요: 외래키 있는 것 먼저 삭제
DROP TABLE IF EXISTS loan;
DROP TABLE IF EXISTS book;
DROP TABLE IF EXISTS sns_user;
DROP TABLE IF EXISTS member;

-- =============================================
-- 1. 회원 테이블 (일반 로그인)
-- =============================================
CREATE TABLE member (
    id        BIGINT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    userId    VARCHAR(50)  NOT NULL UNIQUE,
    password  VARCHAR(255) NOT NULL,
    userName  VARCHAR(50)  NOT NULL,
    email     VARCHAR(255) NOT NULL UNIQUE,
    phone     VARCHAR(20),
    userRole  VARCHAR(20)  DEFAULT 'ROLE_USER',
    joinDate  DATE         DEFAULT (CURRENT_DATE)
);

-- =============================================
-- 2. SNS 회원 테이블 (소셜 로그인)
-- =============================================
CREATE TABLE sns_user (
    id         BIGINT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    name       VARCHAR(100) NOT NULL,
    email      VARCHAR(255) NOT NULL,
    provider   VARCHAR(50)  NOT NULL,
    providerId VARCHAR(100) NOT NULL,
    picture    VARCHAR(500) NOT NULL DEFAULT '',
    userRole   VARCHAR(20)  DEFAULT 'ROLE_USER',
    joinDate   DATE         DEFAULT (CURRENT_DATE),
    UNIQUE KEY uq_sns_provider (provider, providerId)
);

-- =============================================
-- 3. 도서 테이블
-- =============================================
CREATE TABLE book (
    id                BIGINT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    title             VARCHAR(255) NOT NULL,
    author            VARCHAR(100) NOT NULL,
    publisher         VARCHAR(100),
    isbn              VARCHAR(20) UNIQUE,
    category          VARCHAR(50),
    totalQuantity     INT NOT NULL DEFAULT 1,
    availableQuantity INT NOT NULL DEFAULT 1,
    publishDate       VARCHAR(20),
    description       VARCHAR(1000)
);

-- =============================================
-- 4. 대출 테이블
-- =============================================
CREATE TABLE loan (
    id                 BIGINT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    userEmail          VARCHAR(255) NOT NULL,
    userName           VARCHAR(100) NOT NULL,
    bookId             BIGINT NOT NULL,
    loanDate           DATE NOT NULL DEFAULT (CURRENT_DATE),
    expectedReturnDate DATE NOT NULL,
    returnDate         DATE,
    loanStatus         VARCHAR(20) NOT NULL DEFAULT 'BORROWED',
    FOREIGN KEY (bookId) REFERENCES book(id)
);

